/**
 * Emit readable Node hook modules from src/hooks and keep the installed mirror current.
 * --check compares bytes without writing; --write refreshes declared modules and mirrors.
 * Typechecking belongs to tsconfig.hooks.json rather than this isolated transpilation step.
 */
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";

const GENERATED = "// Generated by scripts/generate-hook-runtime.mjs";

/** Find literal patterns without mistaking comments or ordinary strings for regexes.
 * Throws when a constructor's pattern needs runtime evaluation and cannot be checked here.
 */
function literalRegexPattern(node) {
  if (ts.isRegularExpressionLiteral(node)) return node.text;
  if (
    (ts.isNewExpression(node) || ts.isCallExpression(node)) &&
    ts.isIdentifier(node.expression) &&
    node.expression.text === "RegExp"
  ) {
    const argument = node.arguments?.[0];
    if (argument === undefined) return "";
    if (
      ts.isStringLiteralLike(argument) ||
      ts.isRegularExpressionLiteral(argument)
    )
      return argument.text;
    throw new Error(
      `Hook regex constructors require a literal pattern: ${node.getSourceFile().fileName}`,
    );
  }
  return null;
}

/** Reject non-ASCII shorthand classes before generated outputs can be written.
 * Throws on forbidden literal patterns, leaving both runtime trees unchanged.
 */
function checkHookRegexPatterns(text, source) {
  const tree = ts.createSourceFile(source, text, ts.ScriptTarget.ES2022, true);
  function visit(node) {
    const pattern = literalRegexPattern(node);
    if (pattern !== null && /(?:^|[^\\])(?:\\\\)*\\[sSwWdDpP]/u.test(pattern)) {
      throw new Error(`Hook regex must use explicit ASCII classes: ${source}`);
    }
    ts.forEachChild(node, visit);
  }
  visit(tree);
}

/**
 * Collect regular modules in stable path order without following symbolic links.
 * Throws on unreadable directories or symbolic-link entries before output writes.
 */
function listModules(directory, extension) {
  const files = [];
  if (!existsSync(directory)) return files;
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...listModules(path, extension));
    else if (entry.isFile() && entry.name.endsWith(extension)) files.push(path);
    else if (entry.isSymbolicLink()) {
      throw new Error(`Hook runtime tree contains a symbolic link: ${path}`);
    }
  }
  return files.sort();
}

/**
 * Compile every source before allowing either runtime tree to be written.
 * Throws on unreadable sources or compiler diagnostics before either runtime tree is written.
 */
function transpileHookModules(sources, sourceRoot, root, version) {
  const generated = new Map();
  for (const source of sources) {
    const text = readFileSync(source, "utf8");
    checkHookRegexPatterns(text, source);
    const result = ts.transpileModule(text, {
      fileName: source,
      reportDiagnostics: true,
      compilerOptions: {
        target: ts.ScriptTarget.ES2022,
        module: ts.ModuleKind.NodeNext,
        removeComments: false,
        newLine: ts.NewLineKind.LineFeed,
        sourceMap: false,
        declaration: false,
      },
    });
    for (const diagnostic of result.diagnostics ?? []) {
      if (diagnostic.category === ts.DiagnosticCategory.Error) {
        throw new Error(
          ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n"),
        );
      }
    }
    const modulePath = relative(sourceRoot, source).replace(/\.mts$/u, ".mjs");
    const sourcePath = relative(root, source).split(sep).join("/");
    const banner = `${GENERATED} from ${sourcePath}\n// goat-flow-hook-version: ${version}\n`;
    const emitted = result.outputText;
    const shebangEnd = emitted.startsWith("#!") ? emitted.indexOf("\n") + 1 : 0;
    generated.set(
      modulePath,
      emitted.slice(0, shebangEnd) + banner + emitted.slice(shebangEnd),
    );
  }
  return generated;
}

/**
 * Retain canonical helpers and reject unreviewed orphan modules in either tree.
 * Throws on unreadable helpers or orphans, leaving both runtime trees unchanged.
 */
function collectRuntimeModules(generated, canonicalRoot, mirrorRoot) {
  const expected = new Map(generated);
  for (const path of listModules(canonicalRoot, ".mjs")) {
    const name = relative(canonicalRoot, path);
    if (generated.has(name)) continue;
    const bytes = readFileSync(path, "utf8");
    if (bytes.includes(GENERATED)) {
      throw new Error(`Orphan generated hook requires removal review: ${name}`);
    }
    expected.set(name, bytes);
  }
  for (const path of listModules(mirrorRoot, ".mjs")) {
    const name = relative(mirrorRoot, path);
    if (!expected.has(name)) {
      throw new Error(`Orphan installed hook requires removal review: ${name}`);
    }
  }
  return expected;
}

/**
 * Compare expected bytes or refresh validated runtime files in both trees.
 * Writes: --write replaces outputs; --check never writes.
 * Throws on stale output or filesystem failure; a failed write may leave earlier files refreshed.
 */
function writeOrCheckRuntimeFiles(outputs, mode, root) {
  if (mode === "--check") {
    for (const [path, bytes] of outputs) {
      if (!existsSync(path) || readFileSync(path, "utf8") !== bytes) {
        throw new Error(
          `Hook runtime is stale: ${relative(root, path)}; run generate-hook-runtime.mjs --write`,
        );
      }
    }
  } else {
    for (const [path, bytes] of outputs) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, bytes);
    }
  }
}

/**
 * Generate source-owned modules and compare or refresh both runtime trees.
 * Existing hand-maintained .mjs files stay canonical; orphans require explicit removal review.
 * Throws on input, compiler, drift or filesystem failure; a failed write may leave earlier files refreshed.
 *
 * @param {string} root - repository or isolated fixture root containing package metadata
 * @param {"--check" | "--write"} mode - compare only or refresh expected output files
 * @returns {number} number of output files compared or written
 */
export function generateHookRuntime(root, mode) {
  if (mode !== "--check" && mode !== "--write") {
    throw new Error("Expected --write or --check");
  }
  const version = JSON.parse(
    readFileSync(join(root, "package.json"), "utf8"),
  ).version;
  const lock = JSON.parse(
    readFileSync(join(root, "package-lock.json"), "utf8"),
  );
  if (ts.version !== lock.packages["node_modules/typescript"]?.version) {
    throw new Error("Resolved typescript differs from package-lock.json");
  }
  const sourceRoot = join(root, "src/hooks");
  const sources = listModules(sourceRoot, ".mts");
  if (sources.length === 0) throw new Error("No hook runtime sources found");
  const canonicalRoot = join(root, "workflow/hooks");
  const mirrorRoot = join(root, ".goat-flow/hooks");
  const generated = transpileHookModules(sources, sourceRoot, root, version);
  const expected = collectRuntimeModules(generated, canonicalRoot, mirrorRoot);
  const outputs = new Map();
  for (const [name, bytes] of generated)
    outputs.set(join(canonicalRoot, name), bytes);
  for (const [name, bytes] of expected)
    outputs.set(join(mirrorRoot, name), bytes);
  writeOrCheckRuntimeFiles(outputs, mode, root);
  return outputs.size;
}

if (
  process.argv[1] &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url
) {
  const mode = process.argv[2] ?? "--check";
  try {
    const count = generateHookRuntime(resolve(import.meta.dirname, ".."), mode);
    console.log(
      `PASS: hook runtime ${mode === "--check" ? "matches" : "generated"} (${count} files)`,
    );
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
