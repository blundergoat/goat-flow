/**
 * Ship the locked YAML parser and its license so installed policy hooks work without the target project's node_modules.
 *
 * Use --write after changing the locked parser; use --check before releasing or installing the framework.
 * Verification rejects a stale artifact or a resolved dependency version that differs from the lockfile.
 */
import { createRequire } from "node:module";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const require = createRequire(import.meta.url);
const packagePath = require.resolve("js-yaml/package.json");
const version = JSON.parse(readFileSync(packagePath, "utf8")).version;
const locked = JSON.parse(
  readFileSync(resolve(root, "package-lock.json"), "utf8"),
).packages["node_modules/js-yaml"].version;
// A parser version differing from the lockfile cannot become the selected project's shipped policy reader.
if (version !== locked)
  throw new Error("Resolved js-yaml differs from package-lock.json");
const packageRoot = dirname(packagePath);
const license = readFileSync(resolve(packageRoot, "LICENSE"), "utf8");
const source = readFileSync(
  resolve(packageRoot, "dist/js-yaml.min.js"),
  "utf8",
);
const output = resolve(root, "workflow/hooks/vendor/js-yaml.cjs");
const artifact = `/* Generated by scripts/generate-hook-policy-parser.mjs; js-yaml ${version}\n${license}*/\n${source}`;
const mode = process.argv[2] ?? "--check";
// An explicit write regenerates the bundled parser and license for later project installs.
if (mode === "--write") {
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, artifact);
  console.log(`Wrote locked js-yaml ${version} with full MIT license`);
  // Check mode verifies release bytes without changing the bundled parser.
} else if (mode === "--check") {
  // Stale bundled bytes stop verification so installs cannot ship a different parser from the locked dependency.
  if (readFileSync(output, "utf8") !== artifact) {
    throw new Error(
      "Policy parser artifact is stale; run generate-hook-policy-parser.mjs --write",
    );
  }
  console.log(
    `PASS: policy parser matches locked js-yaml ${version} and full MIT license`,
  );
} else {
  throw new Error("Expected --write or --check");
}
