/**
 * Bundle the locked GraphQL syntax parser and licence for target-local hooks.
 * --check is read-only; --write replaces the canonical generated artifact.
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { build } from "esbuild";

const root = resolve(import.meta.dirname, "..");
const require = createRequire(import.meta.url);
const packagePath = require.resolve("graphql/package.json");
const version = JSON.parse(readFileSync(packagePath, "utf8")).version;
const lock = JSON.parse(
  readFileSync(resolve(root, "package-lock.json"), "utf8"),
);
for (const name of ["graphql", "esbuild"]) {
  if (
    require(`${name}/package.json`).version !==
    lock.packages[`node_modules/${name}`].version
  ) {
    throw new Error(`Resolved ${name} differs from package-lock.json`);
  }
}
const license = readFileSync(resolve(dirname(packagePath), "LICENSE"), "utf8");
const result = await build({
  stdin: {
    contents: 'export { parse } from "graphql/language/parser.mjs";',
    resolveDir: root,
    sourcefile: "graphql-parser-entry.mjs",
    loader: "js",
  },
  bundle: true,
  platform: "node",
  target: "node20.11",
  format: "cjs",
  minify: true,
  legalComments: "none",
  write: false,
  banner: {
    js: `/* Generated by scripts/generate-hook-graphql-parser.mjs; graphql ${version}\n${license}*/`,
  },
});
const output = resolve(root, "workflow/hooks/vendor/graphql.cjs");
const artifact = result.outputFiles[0].text;
const mode = process.argv[2] ?? "--check";
if (mode === "--write") {
  writeFileSync(output, artifact);
  console.log(`Wrote locked graphql ${version} parser with full MIT licence`);
} else if (mode === "--check") {
  if (readFileSync(output, "utf8") !== artifact) {
    throw new Error(
      "GraphQL parser artifact is stale; run generate-hook-graphql-parser.mjs --write",
    );
  }
  console.log(
    `PASS: GraphQL parser matches locked graphql ${version} and full MIT licence`,
  );
} else {
  throw new Error("Expected --write or --check");
}
